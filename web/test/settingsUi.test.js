import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

test('Settings 个人设置 shows pipeline and nvtokens fields in Chinese', () => {
  const source = readFileSync(new URL('../src/views/Settings.vue', import.meta.url), 'utf8');
  assert.match(source, /注册 每天上限/);
  assert.match(source, /注册并发/);
  assert.match(source, /提链 每个号最多提链多少次/);
  assert.match(source, /提链 单个账号间隔时间多久（分钟）/);
  assert.match(source, /支付 最多重试几次/);
  assert.match(source, /拿RT 最多重试几次/);
  assert.match(source, /手工推送 PLUS 到 nvtokens 出售/);
  assert.match(source, /立即推送现有 PLUS/);
  assert.match(source, /不会自动上架/);
  assert.match(source, /无试用普号手工导出/);
  assert.match(source, /立即推送现有无试用普号/);
  assert.match(source, /立即推送全部账号/);
  assert.match(source, /api\.post\('\/accounts\/dump-no-trial'/);
  assert.match(source, /api\.post\('\/accounts\/dump-all-accounts'/);
  assert.match(source, /确认推送并删除/);
  assert.match(source, /未检测、有试用、检测失败未定性/);
  assert.doesNotMatch(source, /是否开启自动推送 PLUS 到 nvtokens 出售/);
  assert.match(source, /整号 JSON/);
  assert.match(source, /不勾选「默认加入兜底池」/);
  assert.match(source, /最低价多少（元）/);
  assert.match(source, /售价严格按看板 Plus 最低价/);
  assert.match(source, /查询价格的 token\/session/);
  assert.match(source, /测试价格/);
  assert.match(source, /试用 \{\{ formatSuffixRate/);
  assert.match(source, /提链 \{\{ formatSuffixRate/);
  assert.match(source, /api\.put\('\/settings\/pipeline'/);
  assert.match(source, /api\.put\('\/settings\/nvtokens'/);
  assert.match(source, /每行一个/);
  assert.match(source, /席位暂满/);
  assert.match(source, /<textarea[\s\S]*v-model="cloakForm.license_key"/);
  assert.match(source, /api\.post\('\/settings\/nvtokens\/price-board-test'/);
  assert.doesNotMatch(source, /NVTOKENS_API_KEY\s*=/);
  assert.doesNotMatch(source, /scm_session=/);
  assert.match(source, /https:\/\/github.com\/432539\/gpt-plus/);
  assert.match(source, /QQ 群 1109037692/);
});
